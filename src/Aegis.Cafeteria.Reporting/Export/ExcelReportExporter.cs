namespace Aegis.Cafeteria.Reporting.Export;

using System.Globalization;
using System.IO.Compression;
using System.Security;
using System.Text;
using Aegis.Cafeteria.Reporting.Models;

/// <summary>
/// Writes a standards-compliant .xlsx workbook without requiring Microsoft Excel
/// or an Office automation runtime. Each report table is placed on its own sheet;
/// report metadata and KPI metrics are written to a Summary sheet.
/// </summary>
public sealed class ExcelReportExporter : IReportExporter
{
    public string Format => "XLSX";
    public string FileExtension => ".xlsx";

    public Task ExportAsync(ReportDocument report, Stream output, CancellationToken cancellationToken = default)
    {
        using var archive = new ZipArchive(output, ZipArchiveMode.Create, leaveOpen: true);
        var sheets = BuildSheets(report);

        Write(archive, "[Content_Types].xml", ContentTypes(sheets.Count));
        Write(archive, "_rels/.rels", RootRelationships());
        Write(archive, "xl/workbook.xml", Workbook(sheets));
        Write(archive, "xl/_rels/workbook.xml.rels", WorkbookRelationships(sheets.Count));
        Write(archive, "xl/styles.xml", Styles());

        for (var i = 0; i < sheets.Count; i++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            Write(archive, $"xl/worksheets/sheet{i + 1}.xml", Worksheet(sheets[i], cancellationToken));
        }
        return Task.CompletedTask;
    }

    private static List<Sheet> BuildSheets(ReportDocument report)
    {
        var sheets = new List<Sheet>();
        var summaryRows = new List<Row>
        {
            Row.Text("Report", report.Title),
            Row.Text("Description", report.Subtitle),
            Row.Text("From", report.Filter.From.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)),
            Row.Text("To", report.Filter.To.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)),
            Row.Text("Generated", report.GeneratedAt.LocalDateTime.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)),
            Row.Text("Generated by", string.IsNullOrWhiteSpace(report.GeneratedBy) ? "Cafeteria" : report.GeneratedBy!)
        };
        if (report.Metrics.Count > 0)
        {
            summaryRows.Add(Row.Blank());
            summaryRows.Add(new Row([Cell.Header("Metric"), Cell.Header("Value"), Cell.Header("Note")]));
            foreach (var metric in report.Metrics)
                summaryRows.Add(new Row([Cell.Text(metric.Label), Cell.Number(metric.Value, metric.Format), Cell.Text(metric.Note ?? string.Empty)]));
        }
        if (report.Warnings is { Count: > 0 })
        {
            summaryRows.Add(Row.Blank());
            summaryRows.Add(new Row([Cell.Header("Warnings")]));
            foreach (var warning in report.Warnings) summaryRows.Add(new Row([Cell.Text(warning)]));
        }
        sheets.Add(new Sheet("Summary", summaryRows));

        var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Summary" };
        foreach (var table in report.Tables)
        {
            var rows = new List<Row>
            {
                new(table.Columns.Select(c => Cell.Header(c.Heading)).ToArray())
            };
            foreach (var source in table.Rows)
            {
                rows.Add(new Row(table.Columns.Select(c => ToCell(source.GetValueOrDefault(c.Key), c.Format)).ToArray()));
            }
            sheets.Add(new Sheet(UniqueSheetName(table.Title, used), rows));
        }

        if (report.Charts.Count > 0)
        {
            var chartRows = new List<Row>();
            foreach (var chart in report.Charts)
            {
                chartRows.Add(new Row([Cell.Header(chart.Title)]));
                chartRows.Add(new Row([Cell.Header("Category"), .. chart.Series.Select(s => Cell.Header(s.Name))]));
                for (var i = 0; i < chart.Labels.Count; i++)
                {
                    var cells = new List<Cell> { Cell.Text(chart.Labels[i]) };
                    foreach (var series in chart.Series)
                        cells.Add(Cell.Number(i < series.Values.Count ? series.Values[i] : 0m, series.Format));
                    chartRows.Add(new Row(cells));
                }
                chartRows.Add(Row.Blank());
            }
            sheets.Add(new Sheet(UniqueSheetName("Chart Data", used), chartRows));
        }
        return sheets;
    }

    private static Cell ToCell(object? value, string format) => value switch
    {
        null => Cell.Text(string.Empty),
        decimal d => Cell.Number(d, format),
        double d => Cell.Number((decimal)d, format),
        int i => Cell.Number(i, format == "text" ? "integer" : format),
        long l => Cell.Number(l, format == "text" ? "integer" : format),
        DateTimeOffset dto => Cell.Text(dto.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)),
        DateOnly date => Cell.Text(date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)),
        _ => Cell.Text(Convert.ToString(value, CultureInfo.CurrentCulture) ?? string.Empty)
    };

    private static string UniqueSheetName(string source, HashSet<string> used)
    {
        var invalid = new HashSet<char>(['[', ']', ':', '*', '?', '/', '\\']);
        var clean = new string(source.Where(c => !invalid.Contains(c)).ToArray()).Trim();
        if (string.IsNullOrWhiteSpace(clean)) clean = "Report";
        if (clean.Length > 31) clean = clean[..31];
        var candidate = clean;
        var suffix = 2;
        while (!used.Add(candidate))
        {
            var tail = $" {suffix++}";
            candidate = clean[..Math.Min(clean.Length, 31 - tail.Length)] + tail;
        }
        return candidate;
    }

    private static string Worksheet(Sheet sheet, CancellationToken cancellationToken)
    {
        var sb = new StringBuilder("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?><worksheet xmlns=\"http://schemas.openxmlformats.org/spreadsheetml/2006/main\"><sheetViews><sheetView workbookViewId=\"0\"/></sheetViews><sheetFormatPr defaultRowHeight=\"15\"/><cols><col min=\"1\" max=\"1\" width=\"28\" customWidth=\"1\"/><col min=\"2\" max=\"40\" width=\"18\" customWidth=\"1\"/></cols><sheetData>");
        for (var r = 0; r < sheet.Rows.Count; r++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            sb.Append("<row r=\"").Append(r + 1).Append("\">");
            var row = sheet.Rows[r];
            for (var c = 0; c < row.Cells.Count; c++)
            {
                var cell = row.Cells[c];
                var reference = ColumnName(c + 1) + (r + 1).ToString(CultureInfo.InvariantCulture);
                if (cell.IsNumber)
                {
                    sb.Append("<c r=\"").Append(reference).Append("\" s=\"").Append(StyleIndex(cell.Format)).Append("\"><v>")
                      .Append(cell.NumberValue.ToString(CultureInfo.InvariantCulture)).Append("</v></c>");
                }
                else
                {
                    sb.Append("<c r=\"").Append(reference).Append("\" t=\"inlineStr\" s=\"").Append(cell.IsHeader ? 1 : 0).Append("\"><is><t xml:space=\"preserve\">")
                      .Append(Xml(cell.TextValue)).Append("</t></is></c>");
                }
            }
            sb.Append("</row>");
        }
        sb.Append("</sheetData><autoFilter ref=\"A1:").Append(ColumnName(Math.Max(1, sheet.Rows.FirstOrDefault()?.Cells.Count ?? 1))).Append("1\"/><pageMargins left=\"0.3\" right=\"0.3\" top=\"0.5\" bottom=\"0.5\" header=\"0.2\" footer=\"0.2\"/></worksheet>");
        return sb.ToString();
    }

    private static int StyleIndex(string format) => format switch
    {
        "currency" => 2,
        "integer" => 3,
        "percent" => 4,
        _ => 5
    };

