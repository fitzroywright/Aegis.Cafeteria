namespace Aegis.Cafeteria.Reporting.Export;

using System.Globalization;
using System.Text;
using Aegis.Cafeteria.Reporting.Models;

/// <summary>
/// Lightweight dependency-free PDF exporter. It intentionally renders reports as
/// clean printable text/tables so deployment does not require Office, a browser,
/// or a native PDF engine.
/// </summary>
public sealed class PdfReportExporter : IReportExporter
{
    public string Format => "PDF";
    public string FileExtension => ".pdf";

    public Task ExportAsync(ReportDocument report, Stream output, CancellationToken cancellationToken = default)
    {
        var pages = BuildPages(report, cancellationToken);
        WritePdf(output, pages);
        return Task.CompletedTask;
    }

    private static List<List<PdfLine>> BuildPages(ReportDocument report, CancellationToken cancellationToken)
    {
        var pages = new List<List<PdfLine>> { new List<PdfLine>() };
        var page = pages[0];
        void Line(string text = "", int size = 9, bool bold = false)
        {
            if (page.Count >= 50)
            {
                page = new List<PdfLine>();
                pages.Add(page);
            }
            page.Add(new PdfLine(text, size, bold));
        }

        Line(report.Title, 18, true);
        Line(report.Subtitle, 10);
        Line($"Period: {report.Filter.From:yyyy-MM-dd} to {report.Filter.To:yyyy-MM-dd}    Generated: {report.GeneratedAt.LocalDateTime:yyyy-MM-dd HH:mm}", 8);
        if (!string.IsNullOrWhiteSpace(report.GeneratedBy)) Line($"Generated by: {report.GeneratedBy}", 8);
        Line();

        if (report.Metrics.Count > 0)
        {
            Line("SUMMARY", 11, true);
            foreach (var metric in report.Metrics)
                Line($"{metric.Label}: {FormatDecimal(metric.Value, metric.Format)}{(string.IsNullOrWhiteSpace(metric.Note) ? "" : "  -  " + metric.Note)}");
            Line();
        }

        foreach (var table in report.Tables)
        {
            cancellationToken.ThrowIfCancellationRequested();
            Line(table.Title.ToUpperInvariant(), 11, true);
            var widths = Widths(table.Columns);
            Line(FormatRow(table.Columns.Select(c => c.Heading).ToArray(), widths), 7, true);
            Line(new string('-', Math.Min(110, widths.Sum() + widths.Length - 1)), 7);
            foreach (var row in table.Rows)
            {
                cancellationToken.ThrowIfCancellationRequested();
                var values = table.Columns.Select(c => FormatValue(row.GetValueOrDefault(c.Key), c.Format)).ToArray();
                foreach (var wrapped in WrapRow(values, widths)) Line(wrapped, 7);
            }
            Line();
        }

        if (report.Charts.Count > 0)
        {
            Line("CHART DATA", 11, true);
            foreach (var chart in report.Charts)
            {
                Line(chart.Title, 9, true);
                for (var i = 0; i < chart.Labels.Count; i++)
                {
                    var values = chart.Series.Select(s => $"{s.Name}: {FormatDecimal(i < s.Values.Count ? s.Values[i] : 0m, s.Format)}");
                    Line($"{chart.Labels[i]}  {string.Join(" | ", values)}", 7);
                }
                Line();
            }
        }

        if (report.Warnings is { Count: > 0 })
        {
            Line("WARNINGS", 10, true);
            foreach (var warning in report.Warnings) Line(warning, 8);
        }
        return pages;
    }

    private static int[] Widths(IReadOnlyList<ReportColumn> columns)
    {
        if (columns.Count == 0) return [];
        const int total = 108;
        var baseWidth = Math.Max(8, total / columns.Count - 1);
        return columns.Select(c => c.Format is "currency" or "integer" or "number" or "percent" ? Math.Min(14, baseWidth) : baseWidth).ToArray();
    }

    private static IEnumerable<string> WrapRow(string[] values, int[] widths)
    {
        if (values.Length == 0) yield break;
        var remaining = values.ToArray();
        do
        {
            var cells = new string[values.Length];
            var anyMore = false;
            for (var i = 0; i < remaining.Length; i++)
            {
                var width = widths[i];
                var text = remaining[i] ?? string.Empty;
                if (text.Length > width)
                {
                    var cut = text.LastIndexOf(' ', Math.Min(width, text.Length - 1));
                    if (cut < width / 2) cut = width;
                    cells[i] = text[..cut].TrimEnd();
                    remaining[i] = text[cut..].TrimStart();
                    anyMore |= remaining[i].Length > 0;
                }
                else
                {
                    cells[i] = text;
                    remaining[i] = string.Empty;
                }
            }
            yield return FormatRow(cells, widths);
            if (!anyMore) break;
        } while (true);
    }

    private static string FormatRow(string[] values, int[] widths)
    {
        var cells = values.Select((value, i) => (value ?? string.Empty).Length > widths[i] ? value[..widths[i]] : (value ?? string.Empty).PadRight(widths[i]));
        return string.Join(" ", cells).TrimEnd();
    }

    private static string FormatValue(object? value, string format) => value switch
    {
        null => string.Empty,
        decimal d => FormatDecimal(d, format),
        double d => FormatDecimal((decimal)d, format),
        DateTimeOffset dto => dto.ToString("yyyy-MM-dd HH:mm", CultureInfo.CurrentCulture),
        DateOnly date => date.ToString("yyyy-MM-dd", CultureInfo.CurrentCulture),
        _ => Convert.ToString(value, CultureInfo.CurrentCulture) ?? string.Empty
    };

    private static string FormatDecimal(decimal value, string format) => format switch
    {
        "currency" => value.ToString("C2", CultureInfo.CurrentCulture),
        "percent" => value.ToString("0.##", CultureInfo.CurrentCulture) + "%",
        "integer" => value.ToString("N0", CultureInfo.CurrentCulture),
        _ => value.ToString("N2", CultureInfo.CurrentCulture)
    };

    private static void WritePdf(Stream output, IReadOnlyList<List<PdfLine>> pages)
    {
        using var buffer = new MemoryStream();
        var objects = new List<string>();
        objects.Add("<< /Type /Catalog /Pages 2 0 R >>");
        var pageObjectIds = Enumerable.Range(0, pages.Count).Select(i => 4 + i * 2).ToArray();
        objects.Add($"<< /Type /Pages /Count {pages.Count} /Kids [{string.Join(' ', pageObjectIds.Select(x => $"{x} 0 R"))}] >>");
        objects.Add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");

        for (var i = 0; i < pages.Count; i++)
        {
            var pageId = 4 + i * 2;
            var contentId = pageId + 1;
            objects.Add($"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents {contentId} 0 R >>");
            var content = PageContent(pages[i], i + 1, pages.Count);
            var byteLength = Encoding.ASCII.GetByteCount(content);
            objects.Add($"<< /Length {byteLength} >>\nstream\n{content}\nendstream");
        }

        using var writer = new StreamWriter(buffer, Encoding.ASCII, 1024, leaveOpen: true) { NewLine = "\n" };
        writer.Write("%PDF-1.4\n%AEGIS\n");
        writer.Flush();
        var offsets = new List<long> { 0 };
        for (var i = 0; i < objects.Count; i++)
        {
            offsets.Add(buffer.Position);
            writer.Write($"{i + 1} 0 obj\n{objects[i]}\nendobj\n");
            writer.Flush();
        }
        var xref = buffer.Position;
        writer.Write($"xref\n0 {objects.Count + 1}\n0000000000 65535 f \n");
        foreach (var offset in offsets.Skip(1)) writer.Write($"{offset:0000000000} 00000 n \n");
        writer.Write($"trailer\n<< /Size {objects.Count + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n");
        writer.Flush();
        buffer.Position = 0;
        buffer.CopyTo(output);
    }

    private static string PageContent(IReadOnlyList<PdfLine> lines, int page, int pages)
    {
        var sb = new StringBuilder("BT\n/F1 9 Tf\n36 756 Td\n");
        var previousSize = 9;
        foreach (var line in lines)
        {
            if (line.Size != previousSize)
            {
                sb.Append("/F1 ").Append(line.Size).Append(" Tf\n");
                previousSize = line.Size;
            }
            sb.Append('(').Append(PdfEscape(line.Text)).Append(") Tj\n0 -").Append(line.Size + 4).Append(" Td\n");
        }
        sb.Append("/F1 7 Tf\n0 -8 Td\n(Page ").Append(page).Append(" of ").Append(pages).Append(") Tj\nET");
        return sb.ToString();
    }

    private static string PdfEscape(string text)
    {
        var ascii = new string(text.Select(c => c is >= ' ' and <= '~' ? c : '?').ToArray());
        return ascii.Replace("\\", "\\\\").Replace("(", "\\(").Replace(")", "\\)");
    }

    private sealed record PdfLine(string Text, int Size, bool Bold);
}
